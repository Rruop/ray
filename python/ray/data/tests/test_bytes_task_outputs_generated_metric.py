"""
Test for verifying ray_data_bytes_task_outputs_generated Prometheus metric.

This test validates that the "Bytes Generated by Tasks / Second" metric
(ray_data_bytes_task_outputs_generated) is correctly exported to Prometheus.

Usage:
    pytest python/ray/data/tests/test_bytes_task_outputs_generated_metric.py -v -s
"""

import time

import pytest
import requests

import ray
from ray._common.test_utils import wait_for_condition
from ray.data.tests.conftest import restore_data_context  # noqa: F401


def fetch_metrics_from_prometheus(metrics_export_port: int) -> str:
    """Fetch raw metrics from Prometheus endpoint."""
    try:
        response = requests.get(f"http://127.0.0.1:{metrics_export_port}/metrics")
        response.raise_for_status()
        return response.text
    except requests.exceptions.ConnectionError:
        return ""


def get_metric_value(metrics_text: str, metric_name: str) -> float:
    """Extract metric value from Prometheus text format."""
    for line in metrics_text.split("\n"):
        if line.startswith(metric_name) and not line.startswith("#"):
            # Parse lines like: metric_name{labels} value
            parts = line.split()
            if len(parts) >= 2:
                try:
                    return float(parts[-1])
                except ValueError:
                    continue
    return 0.0


def get_all_metric_values(metrics_text: str, metric_name: str) -> list:
    """Extract all metric values for a given metric name (across all labels)."""
    values = []
    for line in metrics_text.split("\n"):
        if line.startswith(metric_name) and not line.startswith("#"):
            parts = line.split()
            if len(parts) >= 2:
                try:
                    values.append(float(parts[-1]))
                except ValueError:
                    continue
    return values


